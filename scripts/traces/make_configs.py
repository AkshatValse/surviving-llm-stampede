"""Write configs/workload_trace_<source>.yaml (proposed simulator workloads) from results/traces_summary/<source>/summary.json.

  python -I scripts/traces/make_configs.py SOURCE --config configs/traces_analysis.yaml

Field names follow src/prefixmeta/workload.py WorkloadParams. Mapping used (see notes/lit/AGENT_TRACES.md):
  initial_context_tokens = mean prompt size of the first model call of a session (conversation / trajectory)
  new_prompt_tokens      = mean tokens appended between two consecutive calls beyond the previous input + output (delta_ctx),
                           context-compaction events (negative delta) excluded, winsorised at the 99.9th percentile
  decode_tokens          = mean output tokens per model call (winsorised at the 99.9th percentile)
  mean_turns, max_turns  = geometric parameter such that E[min(Geometric(1/mean_turns), max_turns)] equals the observed mean number of
                           model calls per agentic episode capped at max_turns (the workload of record's cap, 60)
  tool_time_*            = the per-turn idle interval between the end of one model call and the next request: for TraceLab the
                           per-round value (last tool result minus last tool request), for mini-SWE-agent the per-step command time
Only `workload` runs with the current code; `workload_empirical` and `workload_lognormal_mixture2` need the other agent's code.
"""
from __future__ import annotations

import argparse
import json
import os
import subprocess

import yaml


def fmt_list(xs, nd=4) -> str:
    return "[" + ", ".join(f"{x:.{nd}g}" for x in xs) + "]"


# which summary series / token group is the headline of each source
HEAD = {
    "tracelab": {"series": "round_z_nohuman|all", "group": "all", "label": "SyFI TraceLab (Claude Code + Codex CLI sessions)",
                 "series_desc": "per-turn idle interval (last tool result - last tool request of the model call), tool calls of all kinds except "
                                "human-interaction tools (AskUserQuestion, ExitPlanMode, ...), wall clock as logged"},
    "mini_swe_v2": {"series": "phase_wall|all", "group": "all", "label": "mini-SWE-agent v2.0.0 on SWE-bench Verified (5 models, 100 paired instances each)",
                    "series_desc": "per-step shell command wall time in the SWE-bench docker container (60 s harness timeout, censored)"},
}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("source")
    ap.add_argument("--config", default="configs/traces_analysis.yaml")
    a = ap.parse_args()
    with open(a.config, encoding="utf-8") as f:
        cfg = yaml.safe_load(f)
    src = cfg["sources"][a.source]
    M = int(cfg["analysis"]["max_turns_workload_of_record"])
    with open(os.path.join(src["summary_dir"], "summary.json"), encoding="utf-8") as f:
        S = json.load(f)
    h = HEAD[a.source]
    ser = S["series"][h["series"]]
    tok = S["tokens"][h["group"]]
    trn = S["turns"][h["group"]]
    L0 = tok["first_input_total_per_session"]["mean"]
    delta = tok["delta_ctx_nonneg"]["mean_w999"]
    dec = tok["output_tokens_per_round"]["mean_w999"]
    geo = trn["geometric_match_agentic"][str(M)]
    mean_turns = geo["mean_turns_geometric"]
    cap = ser["capped600"]
    ln = ser["lognormal_capped600"]
    mixp = ser["mixture2_pos_capped600"]
    atom = ser["atom_frac_lt_floor"]
    q = ser["quantiles_1_99"]
    commit = subprocess.run(["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True, check=True).stdout.strip()
    tq_mean = sum(q) / len(q)
    lines = []
    w = lines.append
    w(f"# PROPOSED simulator workload from real agent traces: {h['label']}.")
    w(f"# Generated by scripts/traces/make_configs.py (repo commit {commit}) from {src['summary_dir']}/summary.json. Not used by any run yet.")
    w("# Method, definitions and caveats: notes/lit/AGENT_TRACES.md.")
    w(f"# Tool-time series: {h['series_desc']}.")
    w("#")
    w("# `workload`                     runs with the current src/prefixmeta/workload.py (tool_time_dist: lognormal is supported).")
    w("# `workload_empirical`           NEEDS the other agent's code: tool_time_dist: empirical + tool_time_quantiles (1st..99th percentile).")
    w("# `workload_lognormal_mixture2`  NEEDS new code: two-component lognormal mixture (keys tool_time_mix_*), plus an atom at ~0.")
    w("# Keys outside WorkloadParams: tool_time_quantiles, tool_time_mix_*, tool_time_atom_*. WorkloadParams.from_dict would reject them today.")
    w("#")
    w(f"# Token mapping: initial_context_tokens = mean first-call prompt of a session; new_prompt_tokens = mean tokens appended between two calls beyond the")
    w(f"# previous input+output (context compactions excluded, winsorised at p99.9); decode_tokens = mean output tokens per call (winsorised at p99.9).")
    w(f"# mean_turns = geometric parameter reproducing the observed mean calls per agentic episode (capped at max_turns = {M}):")
    w(f"# observed mean {geo['target_mean_capped']:.2f} capped, median {trn['episode_rounds_agentic']['median']:.0f}, p90 {trn['episode_rounds_agentic']['p90']:.0f}, p99 {trn['episode_rounds_agentic']['p99']:.0f}.")
    w("# NOTE the trace turn counts are not geometric (see AGENT_TRACES.md); this only matches the mean.")
    w("")
    base = [
        ("initial_context_tokens", f"{int(round(L0))}"),
        ("new_prompt_tokens", f"{int(round(delta))}"),
        ("decode_tokens", f"{int(round(dec))}"),
        ("mean_turns", f"{mean_turns:.4g}"),
        ("max_turns", f"{M}"),
    ]
    w("workload:")
    for k, v in base:
        w(f"  {k}: {v}")
    mp = ln["mean_preserving"]
    w(f"  tool_time_mean_s: {mp['mean']:.4g}          # sample mean of the series capped at {cfg['analysis']['cap_s']:.0f} s (uncapped mean {ser['raw']['mean']:.4g} s)")
    w("  tool_time_dist: lognormal")
    w(f"  tool_time_cv: {mp['cv']:.4g}               # the CV that minimises the KS distance at this mean: KS {mp['ks']:.3f}")
    w(f"  # alternatives: MLE lognormal mean {ln['mean_implied']:.4g} s, CV {ln['cv_implied']:.4g} (KS {ln['ks']:.3f}); moment-matched CV {ln['moment_matched']['cv']:.4g} (KS {ln['moment_matched']['ks']:.3f})")
    w("")
    w("workload_empirical:             # NEEDS the other agent's code")
    for k, v in base:
        w(f"  {k}: {v}")
    w(f"  tool_time_mean_s: {cap['mean']:.4g}          # sample mean of the series capped at {cfg['analysis']['cap_s']:.0f} s (uncapped: {ser['raw']['mean']:.4g}; mean of the 99-point table: {tq_mean:.4g})")
    w("  tool_time_dist: empirical")
    w(f"  tool_time_cv: {cap['cv']:.4g}")
    w("  tool_time_quantiles: " + fmt_list(q))
    w(f"  # tool_time_quantiles = 1st..99th percentile in seconds ({len(q)} values); values above the 99th percentile are not represented")
    w(f"  # (the raw series has {ser['frac_gt_cap'] * 100:.2f}% of values above {cfg['analysis']['cap_s']:.0f} s and {ser['time_share_gt_60s'] * 100:.0f}% of its total time in values above 60 s).")
    w("")
    w("workload_lognormal_mixture2:    # NEEDS new code")
    for k, v in base:
        w(f"  {k}: {v}")
    w(f"  tool_time_mean_s: {cap['mean']:.4g}")
    w("  tool_time_dist: lognormal_mixture2")
    w(f"  tool_time_cv: {cap['cv']:.4g}")
    c1, c2 = mixp["components"]
    w(f"  tool_time_atom_frac: {atom:.4g}        # P(tool time < {cfg['analysis']['floor_s']:.2g} s): treat as ~0 s")
    w(f"  tool_time_mix_weights: [{c1['weight']:.4g}, {c2['weight']:.4g}]   # of the remaining (positive) part")
    w(f"  tool_time_mix_medians_s: [{c1['median_s']:.4g}, {c2['median_s']:.4g}]")
    w(f"  tool_time_mix_sigmas: [{c1['sigma']:.4g}, {c2['sigma']:.4g}]     # sigma of log(seconds)")
    w(f"  # EM fit on the positive part capped at {cfg['analysis']['cap_s']:.0f} s; KS distance to the positive part {mixp['ks']:.3f}")
    out = os.path.join("configs", f"workload_trace_{a.source}.yaml")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    # check it parses
    with open(out, encoding="utf-8") as f:
        d = yaml.safe_load(f)
    assert set(d) == {"workload", "workload_empirical", "workload_lognormal_mixture2"}, d.keys()
    assert len(d["workload_empirical"]["tool_time_quantiles"]) == 99
    print("wrote", out)


if __name__ == "__main__":
    main()
