"""Golden cells for the bit-identity test of the DEFAULT engine configuration (``batching: mixed``).

``tests/data/mixed_golden.json`` was generated by ``python tests/golden_cells.py`` from the UNMODIFIED engine at commit 44dd21f (before the
``batching`` option existed). ``tests/test_batching.py`` re-runs every cell and compares the summary (minus wall-clock fields), the SHA-256
of all windows and of the queue trace bit for bit. The cells cover the three allocation modes, closed / burst / cold-start-with-cap plans,
FCFS / LPM / aging-LPM / TTL-pin policies and the 'whole' victim-eviction sensitivity. (``tests/data/r4_golden.json`` independently pins the
round-4 full_reserve cells.)

This module is deliberately not named ``test_*``: pytest does not collect it.
"""
from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path
from typing import Any, Dict

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO / "src"))

from prefixmeta.mech_runner import load_mech_config                      # noqa: E402
from prefixmeta.r4_runner import closed_spec                              # noqa: E402
from prefixmeta.sim import RunSpec, deep_update, simulate                 # noqa: E402
from prefixmeta.workload import ArrivalPlan                               # noqa: E402

CFG5 = REPO / "configs" / "prefix_meta_r5.yaml"
GOLDEN = REPO / "tests" / "data" / "mixed_golden.json"
LAM = 0.047418947368421054                    # lambda_miss of the round-1 E0 (full_reserve); used only to size the open cells

EXTRA_POLICIES = {"ttl_fcfs": {"kind": "fcfs", "ttl_pin_s": 20.0, "eviction": "lru"},
                  "aging10_lru": {"kind": "aging_lpm", "w_max_s": 10.0, "eviction": "lru"}}


def load_cfg() -> dict:
    return deep_update(load_mech_config(str(CFG5), REPO), {"policies": EXTRA_POLICIES})


def _closed(cfg: dict, policy: str, n: int, seed: int, horizon: float, mode: str, **eo: Any) -> RunSpec:
    cv = dict(cfg["curve"])
    cv["horizon_s"] = horizon
    cv["pool_sessions_per_k"] = 6000
    rs = closed_spec(policy, n, 1.0, seed, cv, cfg["engine"])
    rs.engine_overrides = {"alloc_mode": mode, **eo}
    return rs


def _open(policy: str, seed: int, horizon: float, mode: str, *, rate: float, cold: int = 0, burst: int = 0, t_burst: float = 3000.0,
          cap: int | None = None, **eo: Any) -> RunSpec:
    return RunSpec(exp="g", policy=policy, seed=seed, horizon_s=horizon, variant="g", session_cap_override=cap,
                   plan=ArrivalPlan(kind="constant", horizon_s=horizon, rate=rate, initial_cold=cold, burst_n=burst, burst_t0=t_burst,
                                    burst_width_s=60.0),
                   engine_overrides={"alloc_mode": mode, **eo}, meta={"lam": rate})


def golden_specs(cfg: dict) -> Dict[str, RunSpec]:
    return {
        "full_closed_fcfs_n32_s7400_H8000": _closed(cfg, "fcfs_lru", 32, 7400, 8000.0, "full_reserve"),
        "ratio_closed_fcfs_n40_s7401_H8000": _closed(cfg, "fcfs_lru", 40, 7401, 8000.0, "ratio_reserve"),
        "ratio_closed_lpm_n24_s7402_H8000": _closed(cfg, "lpm_lru", 24, 7402, 8000.0, "ratio_reserve"),
        "ondemand_closed_fcfs_n40_s7403_H8000": _closed(cfg, "fcfs_lru", 40, 7403, 8000.0, "ondemand_preempt"),
        "ondemand_closed_lpm_n24_s7404_H8000": _closed(cfg, "lpm_lru", 24, 7404, 8000.0, "ondemand_preempt"),
        "ratio_closed_whole_victim_n40_s7405_H6000": _closed(cfg, "fcfs_lru", 40, 7405, 6000.0, "ratio_reserve", victim_kv_eviction="whole"),
        "ratio_burst60_fcfs_s7410_H9000": _open("fcfs_lru", 7410, 9000.0, "ratio_reserve", rate=2 * LAM, burst=60),
        "ondemand_cap20_cold300_lpm_s7411_H9000": _open("lpm_lru", 7411, 9000.0, "ondemand_preempt", rate=2 * LAM, cold=300, cap=20),
        "full_burst60_lpm_s7412_H9000": _open("lpm_lru", 7412, 9000.0, "full_reserve", rate=2 * LAM, burst=60),
        "full_aging10_cold100_s7413_H6000": _open("aging10_lru", 7413, 6000.0, "full_reserve", rate=1.5 * LAM, cold=100),
        "full_ttl_cold60_s7414_H6000": _open("ttl_fcfs", 7414, 6000.0, "full_reserve", rate=1.5 * LAM, cold=60),
        "full_nobatch_closed_fcfs_n32_s7415_H3000": _closed(cfg, "fcfs_lru", 32, 7415, 3000.0, "full_reserve", batch_decode_iterations=False),
    }


def digest(res: Dict[str, Any]) -> Dict[str, str]:
    w = json.dumps(res["windows"], sort_keys=True, default=float)
    q = json.dumps([list(map(float, x)) for x in res["qtrace"]])
    return {"windows_sha256": hashlib.sha256(w.encode()).hexdigest(), "qtrace_sha256": hashlib.sha256(q.encode()).hexdigest()}


def run_cell(cfg: dict, rs: RunSpec) -> Dict[str, Any]:
    res = simulate(cfg, rs)
    summary = {k: v for k, v in res["summary"].items() if not k.startswith("wall")}
    return {"n_windows": len(res["windows"]), "summary": json.loads(json.dumps(summary, sort_keys=True, default=float)), **digest(res)}


def main() -> None:
    import subprocess
    cfg = load_cfg()
    cells = {}
    for name, rs in golden_specs(cfg).items():
        cells[name] = run_cell(cfg, rs)
        print("cell", name, "done", flush=True)
    commit = subprocess.run(["git", "rev-parse", "HEAD"], cwd=REPO, capture_output=True, text=True).stdout.strip()
    dirty = bool(subprocess.run(["git", "status", "--porcelain", "--", "src"], cwd=REPO, capture_output=True, text=True).stdout.strip())
    GOLDEN.write_text(json.dumps({"generated_from_commit": commit, "src_dirty": dirty,
                                  "note": "golden outputs of the engine BEFORE the `batching` option; batching=mixed must reproduce them bit for bit",
                                  "cells": cells}, indent=1, sort_keys=True, default=float, allow_nan=True))
    print("wrote", GOLDEN, "from", commit, "src_dirty =", dirty)


if __name__ == "__main__":      # pragma: no cover
    main()
