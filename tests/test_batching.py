def test_invalid_batching_configurations_are_refused(cfg5):
    e = cfg5["engine"]
    with pytest.raises(ValueError):
        EngineParams.from_dict({**e, "batching": "continuous"})
    with pytest.raises(ValueError):                                    # vLLM-like allocation is mixed by construction
        EngineParams.from_dict({**e, "batching": SEP, "alloc_mode": "ondemand_preempt"})
    with pytest.raises(ValueError):
        EngineParams.from_dict({**e, "batching": SEP, "decode_per_seq_s": -1e-6})
    with pytest.raises(TypeError):                                     # a typo in a key must not be silently ignored
        EngineParams.from_dict({**e, "batching": SEP, "prefill_per_tok_s": 1e-4})
    # direct construction bypasses from_dict: the engine itself refuses the unsupported combination
    p = dataclasses.replace(EngineParams.from_dict(e), batching=SEP, alloc_mode="ondemand_preempt")
    wl = WorkloadParams.from_dict(cfg5["workload"])
    from prefixmeta.metrics import Recorder
