def test_prefill_iterations_never_advance_decode_and_memory_and_conservation_hold(cfg5, mode, M, policy, eo):
    eng, specs = _congested(cfg5, mode, M, policy=policy, eo=eo)       # debug=True: check_invariants every engine turn
    s = eng.stats()
    budget = eng.p.prefill_chunk_budget
    P = [x for x in eng.log if x[0] == "P"]
    D = [x for x in eng.log if x[0] == "D"]
    assert len(P) > 50 and len(D) > 50 and s["n_turns_done"] > 100
    assert all(x[5] == 0 for x in P), "a prefill iteration must not advance the decode counter G"
    assert all(1 <= x[3] <= budget for x in P), "new prefill tokens per iteration must respect the chunk budget (full budget, decode does not eat it)"
    if mode == "full_reserve":
        assert all(x[5] == 0 for x in D), "prefill priority: no decode iteration starts while a prefill batch is in progress"
    # time accounting
    assert s["n_prefill_iters"] == len(P) and s["n_decode_iters"] == sum(x[3] for x in D) and s["n_iterations"] == len(P) + sum(x[3] for x in D)
    assert s["prefill_busy_s"] == pytest.approx(sum(x[2] - x[1] for x in P), rel=1e-9)
    assert s["decode_busy_s"] == pytest.approx(sum(x[2] - x[1] for x in D), rel=1e-9)
    assert eng.busy_s == pytest.approx(sum(x[2] - x[1] for x in eng.log), rel=1e-9)
    # memory: occupancy never above M
    assert s["max_resident_tokens"] <= M
    # conservation of sessions, of turns, of first-admission hits
    assert s["n_arrived"] == s["n_sessions_done"] + s["n_in_flight"]
    assert s["n_admitted"] == sum(1 for x in eng.trace if x[0] == "A") and s["n_hits"] == sum(1 for x in eng.trace if x[0] == "A" and x[3])
    if mode == "ratio_reserve":
        assert s["admitted_prefill_tokens"] == s["processed_prefill_tokens"] + s["lost_prefill_tokens"] + sum(r.rem for r in eng.prefill)
        still_waiting = sum(1 for r in eng._waiting.values() if r.resumed)
        assert s["n_preempt"] == s["n_readmit"] + still_waiting


