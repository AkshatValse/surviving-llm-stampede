def lone_latency(e: dict, prompt: int, d: int, sep: bool) -> float:
    """One lone request by explicit iteration arithmetic. sep=False: the shared (mixed) formula; sep=True: per-type keys (no prefill floor)."""
    pf_fixed = e.get("prefill_iter_fixed_s", e["iter_fixed_s"]) if sep else e["iter_fixed_s"]
    pf_tok = e.get("prefill_per_token_s", e["per_token_s"]) if sep else e["per_token_s"]
    dc_fixed = e.get("decode_iter_fixed_s", e["iter_fixed_s"])
    dc_floor = e.get("decode_iter_floor_s", e["iter_floor_s"])
    dc_seq = e.get("decode_per_seq_s", e["per_token_s"])
    t, pos, left = 0.0, 0, prompt
    while left > 0:
        c = min(e["prefill_chunk_budget"], left)
        tok_t = pf_tok * c if sep else max(e["iter_floor_s"], e["per_token_s"] * c)
        t += pf_fixed + tok_t + e["prefill_attn_s"] * c * (pos + c)
        pos += c
        left -= c
    ctx = pos + 1
    for _ in range(d - 1):
        t += dc_fixed + max(dc_floor, dc_seq * 1) + e["decode_attn_s"] * ctx / e["attn_ctx_norm"]
        ctx += 1
    return t


@pytest.mark.parametrize("batch", [True, False])
def test_lone_request_is_unaffected_by_the_batching_mode_and_every_cost_key_is_wired(cfg5, batch):
    """(a) With the fallback keys a lone request (no overlap of prefill and decode, chunks large enough that the mixed floor does not bind)
    takes exactly as long in both modes. (b) With all seven per-type keys set to different values the latency follows the per-type formula,
    which pins that each key is used where the docstring says (a 20000-token prompt = 8192 + 8192 + 3616 prefill tokens)."""
    wo = {"initial_context_tokens": 20000}
    base = {"kv_memory_tokens": 1e6, "batch_decode_iterations": batch}
    lat = {}
    for name, eo in (("mixed", base), ("sep", {**base, "batching": SEP})):
        eng = mk(cfg5, specs_of([(0.0, 1, 0.0)]), wo=wo, eo=eo, horizon=1000.0)
        eng.run(1000.0)
        lat[name] = [x[3] for x in eng.trace if x[0] == "D"][0]
    e = cfg5["engine"]
    assert lat["sep"] == pytest.approx(lat["mixed"], rel=1e-12)
