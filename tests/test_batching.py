# ============================================================================ (4) structure and invariants of congested runs
def _congested(cfg, mode, M, *, seed=11, horizon=900.0, eo=None, policy="fcfs_lru", cap=None, rate=0.5, cold=20, burst=40, batching=SEP):
    wl = WorkloadParams.from_dict(cfg["workload"])
    plan = ArrivalPlan(kind="constant", horizon_s=500.0, rate=rate, initial_cold=cold, burst_n=burst, burst_t0=100.0, burst_width_s=10.0)
    specs = build_specs(wl, plan, seed)
    eng = mk(cfg, specs, policy=policy, eo={"kv_memory_tokens": M, "alloc_mode": mode, "batching": batching, **(eo or {})}, horizon=horizon, cap=cap)
    eng.run(horizon)
    return eng, specs


