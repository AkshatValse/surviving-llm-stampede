    eng = mk(cfg5, specs_of([(0.0, 1, 0.0)]), wo=wo, eo={**base, "batching": SEP, **keys}, horizon=1000.0)
    eng.run(1000.0)
    got = [x[3] for x in eng.trace if x[0] == "D"][0]
    assert got == pytest.approx(lone_latency({**e, **keys}, 20000, 100, sep=True), rel=1e-12)
    assert got != pytest.approx(lat["sep"], rel=1e-3)
    s = eng.stats()
    assert s["n_prefill_iters"] == 3 and s["n_decode_iters"] == 99
    assert s["prefill_busy_s"] == pytest.approx(
        3 * 0.003 + 0.00017 * 20000 + e["prefill_attn_s"] * (8192 * 8192 + 8192 * 16384 + 3616 * 20000), rel=1e-12)


