# ============================================================================ helpers
def specs_of(rows) -> SessionSpecs:
    """rows: (arrival, n_turns, tool_time) per session."""
    n = len(rows)
    nt = np.array([r[1] for r in rows], dtype=np.int64)
    off = np.concatenate([[0], np.cumsum(nt - 1)[:-1]]).astype(np.int64) if n else np.zeros(0, np.int64)
    flat = np.concatenate([np.full(int(r[1]) - 1, float(r[2])) for r in rows]) if n else np.zeros(0)
    return SessionSpecs(arrival=np.array([r[0] for r in rows], dtype=float), n_turns=nt, tool_off=off, tool_flat=flat)


class LogEngine(Engine):
    """Logs every iteration it executes: ('P', t0, t1, new_prefill_tokens, n_decode_idle, dG, n_prefill_before) for a prefill iteration and
    ('D', t0, t1, n_iterations, n_decode, n_prefill_before) for a (possibly batched) run of decode iterations. Also asserts, at every
    completion, that the turn emitted exactly d tokens and sits at its end-of-turn context."""
    log: List[tuple]

    def _iterate_with_prefill(self, planned=None):
        t0, G0, nD, pf0, npf = self.now, self.G, self.n_D, self.processed_prefill_tokens, len(self.prefill)
        super()._iterate_with_prefill(planned)
        self.log.append(("P", t0, self.now, self.processed_prefill_tokens - pf0, nD, self.G - G0, npf))

    def _iterate_decode(self, t_cap, n_cap=None):
        t0, G0, nD, npf = self.now, self.G, self.n_D, len(self.prefill)
        super()._iterate_decode(t_cap, n_cap)
        self.log.append(("D", t0, self.now, self.G - G0, nD, npf))

    def _finish_request(self, req, t):
        if self.wl.decode_tokens > 1:
            if self._dyn:
                assert req.gen + (self.G - req.g_enter) == self.wl.decode_tokens, "a turn must emit exactly d tokens"
            assert req.offs + self.G == req.end, "context at completion != end-of-turn context"
        super()._finish_request(req, t)


def mk(cfg, specs, *, policy="fcfs_lru", wo=None, eo=None, debug=True, horizon=50.0, cap=None, cls=LogEngine) -> Engine:
    rs = RunSpec(exp="t", policy=policy, seed=0, horizon_s=horizon, plan=ArrivalPlan(kind="none", horizon_s=horizon),
                 workload_overrides=wo or {}, engine_overrides=eo or {}, debug=debug, session_cap_override=cap)
    eng, _, _ = build_engine(cfg, rs, specs)
    eng.__class__ = cls
    eng.trace = []
    eng.log = []
    return eng


