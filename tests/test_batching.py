    with pytest.raises(ValueError):
        Engine(p, wl, specs_of([(0.0, 1, 0.0)]), Fcfs(), Recorder(1000.0, 100.0))
    for ok in ("full_reserve", "ratio_reserve"):
        EngineParams.from_dict({**e, "batching": SEP, "alloc_mode": ok})


